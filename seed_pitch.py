def main() -> None:
    init_db()
    with Session(engine) as s:
        s.query(PitchAddon).delete()
        s.query(PitchBlock).delete()
        s.query(TrackFocus).delete()
        s.query(PitchTip).delete()
        s.query(StageQuestion).delete()
        s.flush()

        for data in BLOCKS:
            addons = data.pop("addons")
            block = PitchBlock(**data)
            s.add(block)
            s.flush()
            for i, (label, text, tracks, audience) in enumerate(addons):
                s.add(PitchAddon(
                    block_id=block.id, position=i, label=label,
                    text=text, tracks=tracks, audience=audience,
                ))

        for data in FOCUS:
            s.add(TrackFocus(**data))

        for kind, position, title, body in TIPS:
            s.add(PitchTip(kind=kind, position=position, title=title, body=body))

        for audience, kind, position, text, note in QUESTIONS:
            s.add(StageQuestion(
                audience=audience, kind=kind, position=position, text=text, note=note,
            ))

        s.commit()

        print(f"кирпичей: {s.query(PitchBlock).count()}")
        print(f"добавок:  {s.query(PitchAddon).count()}")
        print(f"акцентов: {s.query(TrackFocus).count()}")
        print(f"подсказок:{s.query(PitchTip).count()}")
        print(f"вопросов: {s.query(StageQuestion).count()}")


if __name__ == "__main__":
    main()
